"""HTTP routes. Thin wrappers: validate input, call the pipeline, return JSON.

Uploads are read into memory (never saved to disk) and size-limited.
Analysis settings are query parameters, so the frontend sends a plain
FormData with a single `file` field.
"""
import math

import pandas as pd
from fastapi import APIRouter, File, HTTPException, Query, Request, UploadFile

from app.schemas import AnalysisResponse, DemoDataResponse, HealthResponse
from app.services.alert_manager import AlertConfig
from app.services.data_loader import DataValidationError
from app.services.detector import DetectorConfig
from app.services.pipeline import DEMO_CSV_PATH, AnalysisConfig, analyze_csv

router = APIRouter()

DEMO_NOTICE = "SYNTHETIC demo data generated by scripts/generate_demo_data.py — not official hackathon data."


def _config(window_days: int, min_history: int, z_threshold: float, cooldown_days: int) -> AnalysisConfig:
    if min_history > window_days:
        raise HTTPException(422, "min_history cannot be larger than window_days.")
    return AnalysisConfig(
        detector=DetectorConfig(window_days=window_days, min_history=min_history, z_threshold=z_threshold),
        alerts=AlertConfig(cooldown_days=cooldown_days),
    )


def _run(content: bytes, config: AnalysisConfig, max_rows: int) -> AnalysisResponse:
    try:
        return analyze_csv(content, config, max_rows)
    except DataValidationError as exc:
        raise HTTPException(422, str(exc)) from exc


WINDOW = Query(28, ge=7, le=90, description="Days of past history used for each baseline")
MIN_HISTORY = Query(14, ge=5, le=60, description="Minimum valid past days before a day is scored")
Z_THRESHOLD = Query(3.5, ge=2.0, le=10.0, description="Sensitivity: lower = more alerts")
COOLDOWN = Query(3, ge=0, le=30, description="Days without a repeat before an alert counts as recovered")


@router.get("/health", response_model=HealthResponse)
def health(request: Request) -> HealthResponse:
    s = request.app.state.settings
    return HealthResponse(status="ok", app=s.app_name, version=s.version)


@router.post("/analyze", response_model=AnalysisResponse)
async def analyze(request: Request, file: UploadFile = File(..., description="CSV of daily campaign metrics"),
                  window_days: int = WINDOW, min_history: int = MIN_HISTORY,
                  z_threshold: float = Z_THRESHOLD, cooldown_days: int = COOLDOWN) -> AnalysisResponse:
    settings = request.app.state.settings
    config = _config(window_days, min_history, z_threshold, cooldown_days)
    if not (file.filename or "").lower().endswith(".csv"):
        raise HTTPException(400, "Only .csv files are accepted.")
    content = await file.read(settings.max_upload_bytes + 1)
    if len(content) > settings.max_upload_bytes:
        raise HTTPException(413, f"File is larger than {settings.max_upload_bytes / 1024 / 1024:g} MB.")
    if not content:
        raise HTTPException(400, "Uploaded file is empty.")
    return _run(content, config, settings.max_rows)


@router.post("/analyze/demo", response_model=AnalysisResponse)
def analyze_demo(request: Request, window_days: int = WINDOW, min_history: int = MIN_HISTORY,
                 z_threshold: float = Z_THRESHOLD, cooldown_days: int = COOLDOWN) -> AnalysisResponse:
    """Analyze the bundled SYNTHETIC demo dataset (no upload needed)."""
    config = _config(window_days, min_history, z_threshold, cooldown_days)
    return _run(DEMO_CSV_PATH.read_bytes(), config, request.app.state.settings.max_rows)


@router.get("/demo-data", response_model=DemoDataResponse)
def demo_data(limit: int = Query(50, ge=1, le=5000)) -> DemoDataResponse:
    df = pd.read_csv(DEMO_CSV_PATH, dtype={"campaign_id": str}, keep_default_na=False)
    records = [{k: (None if isinstance(v, float) and not math.isfinite(v) else v) for k, v in row.items()}
               for row in df.head(limit).to_dict("records")]
    return DemoDataResponse(synthetic=True, notice=DEMO_NOTICE, columns=list(df.columns),
                            total_records=len(df), records=records)
