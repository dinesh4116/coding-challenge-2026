def _draw_stylized_face(draw: ImageDraw.ImageDraw, x: int, y: int, size: int):
    """
    Draws a stylized human face with high contrast eyes, nose, and mouth
    that triggers OpenCV's Haar frontal face detector reliably.
    """
    # Face contour
    draw.ellipse([x - size, y - int(size * 1.2), x + size, y + int(size * 1.2)], fill=(245, 215, 185), outline=(120, 80, 50), width=3)
    # Hair
    draw.chord([x - size - 2, y - int(size * 1.3), x + size + 2, y - int(size * 0.2)], 180, 360, fill=(50, 30, 20))
    # Eyes
    eye_offset = int(size * 0.4)
    eye_y = y - int(size * 0.2)
    eye_r = max(int(size * 0.15), 4)
    # Eye whites
    draw.ellipse([x - eye_offset - eye_r, eye_y - eye_r, x - eye_offset + eye_r, eye_y + eye_r], fill=(255, 255, 255), outline=(50, 50, 50))
    draw.ellipse([x + eye_offset - eye_r, eye_y - eye_r, x + eye_offset + eye_r, eye_y + eye_r], fill=(255, 255, 255), outline=(50, 50, 50))
    # Pupils
    pupil_r = max(int(eye_r * 0.6), 2)
    draw.ellipse([x - eye_offset - pupil_r, eye_y - pupil_r, x - eye_offset + pupil_r, eye_y + pupil_r], fill=(20, 20, 20))
    draw.ellipse([x + eye_offset - pupil_r, eye_y - pupil_r, x + eye_offset + pupil_r, eye_y + pupil_r], fill=(20, 20, 20))
    # Eyebrows
    draw.arc([x - eye_offset - eye_r, eye_y - eye_r - 6, x - eye_offset + eye_r, eye_y - eye_r + 2], 180, 360, fill=(30, 20, 10), width=2)
    draw.arc([x + eye_offset - eye_r, eye_y - eye_r - 6, x + eye_offset + eye_r, eye_y - eye_r + 2], 180, 360, fill=(30, 20, 10), width=2)
    # Nose
    draw.line([x, eye_y + 4, x, y + int(size * 0.2)], fill=(160, 110, 80), width=3)
    # Mouth / Smile
    mouth_y = y + int(size * 0.5)
    mouth_w = int(size * 0.45)
    draw.arc([x - mouth_w, mouth_y - 10, x + mouth_w, mouth_y + 12], 0, 180, fill=(180, 40, 40), width=4)


def create_synthetic_ad_image(
    ad_id: str,
    width: int,
    height: int,
    bg_color: Tuple[int, int, int],
    has_face: bool,
    headline: str,
    subtext: str,
    accent_color: Tuple[int, int, int],
    is_busy: bool = False,
) -> Image.Image:
    """Generates an individual synthetic creative with clear visual design."""
    img = Image.new("RGB", (width, height), color=bg_color)
    draw = ImageDraw.Draw(img)

    # Decorative geometric patterns
    if is_busy:
        for i in range(0, width, 40):
            draw.line([(i, 0), (i + 20, height)], fill=(min(bg_color[0] + 30, 255), min(bg_color[1] + 30, 255), min(bg_color[2] + 30, 255)), width=2)
        # Add confetti / shapes
        for j in range(15):
            rx = (j * 73) % width
            ry = (j * 59) % height
            draw.rectangle([rx, ry, rx + 25, ry + 15], fill=accent_color)
    else:
        # Subtle card container
        margin = int(width * 0.05)
        draw.rounded_rectangle(
            [margin, margin, width - margin, height - margin],
            radius=16,
            outline=accent_color,
            width=3,
        )

    # Face placement
    if has_face:
        face_cx = int(width * 0.5)
        face_cy = int(height * 0.38)
        face_size = int(min(width, height) * 0.18)
        _draw_stylized_face(draw, face_cx, face_cy, face_size)

    # Headline and copy
    text_y = int(height * 0.68) if has_face else int(height * 0.35)
    # Border badge
    draw.rounded_rectangle([int(width * 0.1), text_y - 10, int(width * 0.9), text_y + 40], radius=8, fill=(20, 20, 20, 180))
    draw.text((int(width * 0.15), text_y), headline, fill=(255, 255, 255))

    # Subtext
    draw.text((int(width * 0.15), text_y + 55), subtext, fill=(240, 240, 240))

    # CTA Button
    btn_y = int(height * 0.85)
    btn_w = int(width * 0.6)
    btn_x = int((width - btn_w) / 2)
    draw.rounded_rectangle([btn_x, btn_y, btn_x + btn_w, btn_y + 42], radius=12, fill=accent_color)
    draw.text((btn_x + int(btn_w * 0.25), btn_y + 12), "SHOP NOW", fill=(255, 255, 255))

    # Watermark synthetic label
    draw.text((10, height - 20), f"[SYNTHETIC AD: {ad_id}]", fill=(180, 180, 180))

    return img


